#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""把 mine_vignette.py 的挖掘结果渲染成 13-语料挖掘/07-桥段分布.md。

分工与 render_mining.py 一致：13 卷是机器测出来的数据层，
14-桥段库 是人写的技法层。这里只出数字与结构，不出写法。

用法：python3 render_vignette.py
"""

import json
from collections import Counter, defaultdict

from paths import LIB
from render_mining import deai, table          # 文风铁律与表格渲染复用同一套

SRC = LIB / "10-藏书索引" / "_桥段挖掘.json"
OUT = LIB / "13-语料挖掘" / "07-桥段分布.md"

D = json.loads(SRC.read_text(encoding="utf-8"))
DOCS, HITS = D["docs"], D["hits"]
FAM = dict(D["fam"])
PROP = dict(D["prop"])

# 族名与中文说明从挖掘脚本读，避免两处各自漂移
from mine_vignette import SCENE as _S, REACT as _R, WORLD as _W
SCENE_KEYS = list(_S)
SCENE_CN = {
    "等待": "等人不归", "夜深": "夜深未睡", "反复": "反复加热／重做",
    "做饭": "下厨备饭", "投喂": "喂食入口", "喂药": "喂药服侍",
    "加班": "临时缺席", "失联": "联系不上", "生病": "发烧生病",
    "上药": "擦拭上药", "睡着": "就地睡着", "守夜": "守着不睡",
    "吃醋": "查岗吃醋", "留痕": "身上留痕", "归家": "开门到家",
    "接送": "接送等候", "赠礼": "备礼送礼", "罚": "日常责罚",
    "分手": "提出分手", "婚仪": "婚礼仪式", "停电": "停电烛光", "困电梯": "被困电梯",
    "歌舞": "唱歌跳舞", "误会": "误会与解释", "闺蜜": "闺蜜在场", "卸妆": "卸妆素颜",
    "理发": "剪发理发", "置装": "试衣置装",
}
REACT_KEYS = list(_R)
WORLD_KEYS = list(_W)


SCENE_CN = {k: SCENE_CN.get(k, k) for k in SCENE_KEYS}


def pct(n, d=None):
    return f"{n / (d or DOCS) * 100:.1f}%"


def main():
    L = ["# 桥段分布 · 日常戏由哪几拍构成", "",
         "> **分级** G ｜ 预警 无 ｜ 亚型 全谱系通用",
         f"> 数据来源：{DOCS:,} 部独立作品正文，由 "
         "[`_脚本/mine_vignette.py`](../_脚本/mine_vignette.py) 挖掘、"
         "[`render_vignette.py`](../_脚本/render_vignette.py) 渲染，**可复跑**。",
         "> 这一卷的性质：它是机器测出来的结构真相，不是编者的归纳。"
         "写法在 [14 卷](../14-桥段库/README.md)。", "",
         "---", "", "## 一、判据",
         "",
         "桥段是一串节拍，不是一个词。所以判据用**共现**，不用关键词命中：",
         "",
         f"| 项 | 取值 |",
         "|---|---|",
         f"| 窗口宽度 | {D['win']:,} 字 |",
         f"| 命中条件 | 情境族 ≥{D['min_scene']} 且 反应族 ≥{D['min_react']} |",
         f"| 族数 | 情境 {len(SCENE_KEYS)} · 反应 {len(REACT_KEYS)} · 世界设定 {len(WORLD_KEYS)} |",
         f"| 扫描范围 | {DOCS:,} 部独立作品（非文件数，同作品多份存档只取最长的一份）|",
         f"| 含桥段的作品 | {HITS:,} 部（{pct(HITS)}）|",
         "",
         "为什么要把节拍分成情境与反应两类：反应族（哭／抱／撒娇／道歉）"
         "在任何言情里都高频，它们不定义场景。真正把两场戏区分开的是情境族"
         "（做饭／加班／反复加热／喂药／责罚）。第一版用「任意 3 族共现」，"
         "命中率 99%，组合榜前十全是「哭＋抱＋撒娇」，等于没测。", "",
         "---", "", "## 二、情境族出现率",
         "",
         "口径是**窗口级**：这一族出现在该作品的某个桥段窗口里，才计一次。"
         "书级不算数。六十万字的书里必然出现「哭」。", ""]

    rows = [(SCENE_CN[k], k, f"{FAM.get(k, 0):,}", pct(FAM.get(k, 0)))
            for k in sorted(SCENE_KEYS, key=lambda x: -FAM.get(x, 0))]
    L += table(rows, ["情境", "节拍族", "作品数", "占比"])

    L += ["", "读法：占比高的是这个类型的**刚需日常戏**，写手绕不开；"
          "占比低的是**低竞争位**，写好了辨识度反而高。", "",
          "---", "", "## 三、反应族出现率", "",
          "反应族是情绪落点。它们不区分场景，但它们决定一场戏收在哪里。", ""]
    rows = [(k, f"{FAM.get(k, 0):,}", pct(FAM.get(k, 0)))
            for k in sorted(REACT_KEYS, key=lambda x: -FAM.get(x, 0))]
    L += table(rows, ["反应", "作品数", "占比"])

    # ── 情境组合 = 桥段的经验目录 ────────────────────────────────
    L += ["", "---", "", "## 四、情境组合（桥段的经验目录）", "",
          "两个以上情境族落在同一个窗口里，就是一场成形的日常戏。"
          "下表按作品数排序，**这张表就是桥段库的选目依据**——"
          "14 卷收哪些桥段，由它决定，不由编者的印象决定。", ""]
    rows = []
    for combo, c in D["combo"][:40]:
        parts = combo.split("+")
        rows.append((" ＋ ".join(SCENE_CN.get(p, p) for p in parts),
                     combo, f"{c:,}", pct(c, HITS)))
    L += table(rows, ["组合", "节拍族", "作品数", "占含桥段作品"])

    # ── 有序节拍链 ──────────────────────────────────────────────
    L += ["", "---", "", "## 五、有序节拍链", "",
          "组合只说「哪几拍」，节拍链还说「什么顺序」。"
          "顺序可以照抄。它就是一场戏的骨架。", ""]
    rows = [(seq, f"{c:,}") for seq, c in D["seq"][:30]]
    L += table(rows, ["节拍链", "作品数"])
    L += ["", "注意：链长受窗口宽度限制，最多记到 6 拍。"
          "更长的日常戏会被切成两段分别计数。", ""]

    # ── 道具实测 ────────────────────────────────────────────────
    L += ["---", "", "## 六、道具实测", "",
          "「可用细节」那一格的数据源。方法是**受控词表实测**：词表由编者出，"
          "脚本只回答这个物件在多少部不同作品的桥段窗口里出现过。", "",
          "为什么不用开放式抽取：试过两版都失败了。"
          "第一版用「把／放／拿／递 ＋ X」，抽出来的全是趋向补语"
          "（放下来→「下来」、拿出来→「出来」）；第二版用量词锚定"
          "（一碗汤、那把伞），词性对了但量词也搭配抽象状态"
          "（一片空白、一双漂亮的眼睛），且召回极低。"
          "中文不上分词器做开放域名词抽取，精度和召回都保不住。"
          "受控词表把脚本从发现器降级成验真器，代价是词表外的物件测不到，"
          "换来的是每个数字都可复现。", "",
          "### 6.1 全局高频物件", ""]
    rows = [(w, f"{c:,}", pct(c, HITS)) for w, c in D["prop"][:48]]
    L += table(rows, ["物件", "作品数", "占含桥段作品"])

    # 提升度：某物件在这一场戏里比在一般桥段里高出多少
    by = defaultdict(dict)
    for k, c in D["prop_by_scene"]:
        sc, w = k.split("\t")
        by[sc][w] = c
    L += ["", "### 6.2 各场戏的特征物件（按提升度）", "",
          "上一张表里，门／车／药／手机／灯 在每一场戏里都排前列——"
          "它们是全局高频词，不是某场戏的特征。所以这里算的是**提升度**："
          "该物件在这场戏里的出现率，除以它在一般桥段里的出现率。"
          "倍数越高，越是这场戏专属的东西。", ""]
    # 逐族一行进表格：表格自带结构，不再用加粗当小标题（铁律 3）
    rows = []
    for sc in sorted(SCENE_KEYS, key=lambda x: -FAM.get(x, 0)):
        base_n = FAM.get(sc, 0)
        if base_n < 30 or sc not in by:
            continue
        lifted = []
        for w, c in by[sc].items():
            gw = PROP.get(w, 0)
            if gw < 20 or c < 5:
                continue
            lift = (c / base_n) / (gw / HITS)
            if lift > 1.15:
                lifted.append((lift, w, c))
        lifted.sort(reverse=True)
        if lifted:
            items = "、".join(f"{w}（{l:.1f}×）" for l, w, _ in lifted[:12])
            rows.append(f"| {SCENE_CN[sc]}（{sc}） | {base_n:,} | {items} |")
    if rows:
        L += ["| 场戏 | 作品数 | 特征物件（提升度） |", "|---|---:|---|"] + rows + [""]

    L += ["---", "", "## 七、这份数据测不到什么", "",
          "写清楚边界，比多列两张表有用。", "",
          "| 测不到 | 原因 |",
          "|---|---|",
          "| 词表外的物件 | 受控词表只有 100 余词，写手用的更多 |",
          "| 跨章的长桥段 | 窗口宽 2,500 字，更长的戏会被切成两段 |",
          "| 谁对谁做 | 本脚本不做指代消解，测不出施受方向 |",
          "| 甜向还是虐向 | 同一串节拍两种收法都成立，机器判不了 |",
          "| 古代／星际的等价物 | 节拍族用的是现代词，换皮层要人写 |", "",
          "机器给结构与频次，写法要人补——后三行即两边的分界线，人工的部分在 14 卷。", "",
          "---", "",
          "相关条目：[14-桥段库](../14-桥段库/README.md) · "
          "[05-剧情套路/02-名场面结构库](../05-剧情套路/02-名场面结构库.md) · "
          "[05-名场面分布](05-名场面分布.md)", "",
          f"> 编纂：本表由脚本生成，随 `run.py mine` 重跑。基数 {DOCS:,} 部独立作品。"]

    OUT.write_text(deai("\n".join(L)) + "\n", encoding="utf-8")
    print(f"→ {OUT.relative_to(LIB)}  {len('\n'.join(L)):,} 字符")


if __name__ == "__main__":
    main()
