def parse(p: Path):
    t = p.read_text(encoding="utf-8")
    # 卷首亚型：三行头里「亚型 」之后到行尾/分隔符
    head = "\n".join(t.split("\n")[:14])
    msub = re.search(r"亚型 ?([^｜\n]+)", head)
    sub = msub.group(1).strip() if msub else ""
    out = []
    for blk in re.split(r"^## ", t, flags=re.M)[1:]:
        bhead = blk.split("\n", 1)[0].strip()
        m = re.match(r"([一二三四五六七八九十]+) · (.+)$", bhead)
        if not m:
            continue
        num, name = m.group(1), m.group(2)
        rate = re.search(r"^`([GTME])` *｜ *(⚠️[^｜\n]+|无预警)", blk, re.M)
        skel = re.search(r"^\*\*骨架\*\*｜(.+?)$", blk, re.M)
        # GitHub 式锚点：小写、去标点（含「」，·等全角）、空格→连字符。
        # 曾直接用 {num}--{name}，带标点或大写字母的条目（她给钱，他不要 / KTV）在 GitHub 上全部断链。
        slug = "".join(ch for ch in f"{num} · {name}".lower()
                       if ch.isalnum() or ch in "-_ ").replace(" ", "-")
        wtxt = rate.group(2).strip() if rate else ""
        out.append({
            "num": num, "name": name,
            "rate": rate.group(1) if rate else "T",
            "warn": "⚠️" if wtxt.startswith("⚠️") else "",
            "warn_text": wtxt if wtxt.startswith("⚠️") else "",
            "sub": sub,
            "skel": (skel.group(1) if skel else "").strip(),
            "ex": "#### 示例" in blk,
            "file": p.name,
            "anchor": f"{p.name}#{slug}",
        })
    return out


