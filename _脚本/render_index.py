def render_distribution():
    gb = [r for r in R if is_gb(r)]
    tag_count = Counter(t for r in gb for t in r["文件名标签"])
    L = ["# 亚型分布报告", "",
         f"> 统计口径：**{len(gb)} 篇本类型作品**（已剔除 {len(R)-len(gb)} 篇混入）。",
         "> 标签来自文件名归纳，覆盖率约五成——**未标注 ≠ 没有该亚型**，"
         "真实分布需精读补全。本报告的价值在于找出**语料缺口**。", "",
         "## 一、总量与体量分布", ""]

    buckets = [("A 短篇 <3万", lambda w: w < 3), ("B 中短篇 3-10万", lambda w: 3 <= w < 10),
               ("C 长篇 10-30万", lambda w: 10 <= w < 30), ("D 大长篇 30-60万", lambda w: 30 <= w < 60),
               ("E 超长 >60万", lambda w: w >= 60)]
    L += ["| 体量桶 | 篇数 | 占比 | 合计万字 |", "|---|---:|---:|---:|"]
    for name, f in buckets:
        sel = [r for r in gb if f(r["万字"])]
        L.append(f"| {name} | {len(sel)} | {len(sel)/len(gb)*100:.1f}% "
                 f"| {sum(r['万字'] for r in sel):.0f} |")

    L += ["", "## 二、尺度分布", "",
          "| 尺度 | 篇数 | 占比 | 说明 |", "|---|---:|---:|---|"]
    heat_note = {"G/T(清水向)": "无肉或极淡，适合提炼清水张力技法",
                 "T(微H/擦边)": "有性张力，描写点到为止",
                 "M(有肉)": "明确性内容，概括式处理",
                 "E(高H)": "详细描写，肉戏占比高"}
    hc = Counter(r["尺度推定"] for r in gb)
    for h in sorted(hc, key=lambda x: HEAT_ORDER.get(x, 9)):
        L.append(f"| {h} | {hc[h]} | {hc[h]/len(gb)*100:.1f}% | {heat_note.get(h,'')} |")

    L += ["", "## 三、叙事人称分布", "",
          "文件名从不标注人称，这是本次正文探针的独有发现。", "",
          "| 人称 | 篇数 | 说明 |", "|---|---:|---|"]
    pc = Counter(r["性别配置"] for r in gb)
    for k, v in pc.most_common():
        note = {"GB(第二人称)": "「你」视角，读者代入型——中文网文里的稀有亚型，值得单独研究",
                "GB(第一人称女主)": "女主第一人称，代入感强，独白技法密集",
                "GB(穿书)": "穿进耽美文的元叙事结构"}.get(k, "第三人称为主")
        L.append(f"| {k} | {v} | {note} |")

    L += ["", "## 四、各维度亚型分布", ""]
    for dim, tags in DIMENSIONS.items():
        L += [f"### {dim}", "", "| 亚型 | 篇数 | 代表作（字数最多者） |", "|---|---:|---|"]
        rows = []
        for t in tags:
            sel = [r for r in gb if t in r["文件名标签"]]
            if not sel:
                rows.append((t, 0, "—"))
            else:
                top = max(sel, key=lambda r: r["字数"])
                rows.append((t, len(sel), f"{top['作品名'][:22]}（{top['万字']}万）"))
        for t, n, ex in sorted(rows, key=lambda x: -x[1]):
            flag = " ⚠️缺口" if n <= 1 else ""
            L.append(f"| {t}{flag} | {n} | {esc(ex)} |")
        L.append("")

    L += ["## 五、语料缺口分析", "",
          "标 ⚠️缺口 的亚型在本地藏书中样本 ≤1 篇，意味着：", "",
          "1. **提炼这些亚型时不能靠藏书**——样本量不足以归纳规律，需转向全网研究或原创设计；",
          "2. 若你要写这些方向，库里的相关条目会更依赖理论推演而非语料实证，"
          "使用时请注意 [`【一家之言】`](../00-编纂规约/01-分级与预警体系.md) 类标注；",
          "3. 这也是后续 `_收件箱` 补充素材时的**优先采购清单**。", ""]
    gaps = []
    for dim, tags in DIMENSIONS.items():
        for t in tags:
            n = sum(1 for r in gb if t in r["文件名标签"])
            if n <= 1:
                gaps.append(f"{dim}·{t}({n})")
    L.append("**缺口清单**：" + "、".join(gaps) if gaps else "**无明显缺口。**")

    L += ["", "## 六、来源站分布", "",
          "| 来源 | 篇数 |", "|---|---:|"]
    src = Counter(t for r in gb for t in r["文件名标签"] if t.startswith("源:"))
    for k, v in src.most_common():
        L.append(f"| {k[2:]} | {v} |")
    L.append(f"| 未标注 | {len(gb) - sum(src.values())} |")

    L += ["", "---", "> 由 [`_脚本/render_index.py`](../_脚本/render_index.py) 自动生成"]
    (OUT_DIR / "亚型分布报告.md").write_text("\n".join(L), encoding="utf-8")


