def zh(s):
    return len(re.findall(r"[一-鿿]", s))


EXEMPT = re.compile(r"<!-- ?例外[:：]")
# 来源声明整行不查（铁律 6.2）。带 `>` 前缀的已被上面的行过滤挡住，
# 顶格写的这些没有，补齐：材料来源／数据来源／频次来源／出处／编纂／修订。
SOURCE_LINE = re.compile(r"\s*(?:[^\n：]{0,4}来源|出处|编纂|修订)[:：]")


def strip_noise(t):
    # 带 `<!-- 例外:规则号 理由 -->` 的行整行跳过，与 check_compliance 同一套机制。
    # 库里有两处故意写坏的教学样本（易混淆词辨析的题眼句、反AI味指南病 5 的
    # 三连示例），它们是内容本身，不是病；没有这一层，那两篇会永远标红，
    # 而长期挂着的红灯等于没有红灯。
    if "例外" in t:
        t = "\n".join(l for l in t.split("\n") if not EXEMPT.search(l))

    """去掉代码块、表格、引文、链接、YAML 头，只留散文。"""
    t = re.sub(r"```[\s\S]*?```", "", t)
    # 只剥**文件开头**的 YAML front matter。
    # 原来写的是 flags=re.M 的 ^---，于是正文里任意两条 --- 分隔线之间的
    # 整段都被当成 front matter 删掉——一篇有 6 条分隔线的文档，3 个整段
    # 不参与统计，测出来的密度全是低估。**锚点错一个字符，整套数据失真。**
    t = re.sub(r"\A---\n[\s\S]*?\n---\n", "", t)
    # 非散文的行一律不参与统计。判据是「拿散文的尺量非散文」这条老教训的第三次实例：
    # 前两次是数据表被按散文查密度、短文被按千字算密度。这次是**句子切分**——
    # sentences() 只在 。！？ 处断句，而标题、分隔线、`别称：…｜英文：…｜分级：…`
    # 这类词条元数据行都不带句号，于是一个标题会和后面几行黏成一个「120 字的句子」。
    # 02-术语百科/02 是一部术语词典，317 句里大半是这么黏出来的，
    # 量出来的「短句占比 0.03」说的是它的排版，不是它的写法。
    t = "\n".join(l for l in t.split("\n")
                  if not l.lstrip().startswith(("|", "#", "---", "===", ">"))
                  and not SOURCE_LINE.match(l)
                  and l.count("｜") < 2)
    t = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", t)
    t = re.sub(r"`[^`\n]+`", "", t)
    # 剥引号内的成句引文，与 check_compliance 的 J 项 prep() 同一行为。
    # 理由：引文不是本库写的字，不该参与本库文风的统计。
    # 红线 1.3 禁止为文风指标改动引文，那么也不该让引文替本库背指标——
    # 反过来也一样：引文会稀释分母，把本库自己的密度盖下去。
    # 01-总论/05 的「不是X是Y」5 处全在社群原话与波伏瓦名句里，就是这个情况。
    t = strip_quotes(t)
    # 书名号里的长标题也是别人的字。《四爱和gb是一种感情倾向，不是xp》整个是一篇
    # 知乎文章的题目，本库只是引它，却被算了一处「不是X是Y」。短书名（《风起云涌》）
    # 留着——它是作品名，不是引语。门槛与 strip_quotes 一致。
    t = re.sub(r"《[^》\n]{6,}》", "", t)
    return t


def sentences(t):
    # 空行也是句子边界。不这么切，两个段落之间少一个句号就会黏成一句，
    # 句长分布随之失真（黏出来的长句会把 CV 拉高、把短句占比压低）。
    parts = re.split(r"(?<=[。！？!?])\s*|\n{2,}", t)
    return [zh(p) for p in parts if p and zh(p) >= 2]


def measure(text):
    t = strip_noise(text)
    cn = zh(t) or 1
    sl = sentences(t)
    paras = [zh(p) for p in re.split(r"\n{2,}", t) if zh(p) >= 10]

    m = {"汉字": cn, "句数": len(sl)}

    # 分布层：句长的均值、标准差、变异系数。
    # 人类写作的句长分布是「爆发式」的：短句与长句交替，CV 通常 > 0.5；
    # 模型倾向把每句都写成中等长度，CV 会明显偏低。
    # 节奏类指标要求足够的样本。门槛原是 8 句，太低——
    # 10-藏书索引 那种整篇是数据表的文档，散文只剩几句标题说明，
    # 量出来的「句长 CV 0.41」说的是那几句话，不是这篇文档的写法。
    # 25 句以下不给节奏判据，只查词表与句式（那两类由渲染种子决定，改得动）。
    if len(sl) >= 25:
        mu = statistics.mean(sl)
        sd = statistics.pstdev(sl)
        m["句长均值"] = round(mu, 1)
        m["句长CV"] = round(sd / mu, 2) if mu else 0
        # 极短句（≤6 汉字）的比例。人写东西会甩短句，模型很少
        m["短句占比"] = round(sum(1 for x in sl if x <= 6) / len(sl), 2)
        m["长句占比"] = round(sum(1 for x in sl if x >= 45) / len(sl), 2)
    if len(paras) >= 4:
        pmu = statistics.mean(paras)
        m["段长CV"] = round(statistics.pstdev(paras) / pmu, 2) if pmu else 0

    # 标点丰富度：模型少用逗号以外的标点，尤其是分号、括号、问号。
    # 这两项只报不判——分母里混着术语注解与引注，做不成判据。真正当判据的是下面那条。
    for name, ch in (("分号", "；;"), ("括号", "（(")):
        m[f"{name}/千字"] = round(len(re.findall(f"[{ch}]", t)) / cn * 1000, 1)
    # 长括号：书面语最扎眼的一个手势。
    # 把话说到一半，拿括号补一句——这是公文和论文的写法，写小说和在网上说话的人都不这么干。
    # 实测 85 篇真人小说：中位 0.02／千字，P90 0.21。本库改写前 3.34，是真人的十六倍。
    # 判据只算**正文**（strip_noise 已剥掉表格、三行头、标题），只算**非引注**、
    # 且括号里有七个以上汉字的那种——给术语加三五个字的注解是百科体例，不算病。
    # 交叉引用行（前接／后接／对照／相关条目／可串接）整行不算：那些括号是
    # 「这一条是什么」的一句话注，跟引注同类，是百科体例，不是行文里打岔。
    # 三类行整行不算，它们是元信息不是行文：
    #   · 交叉引用（前接／后接／对照／相关条目）——括号里是「那一条是什么」的注
    #   · 来源声明（E 项要求的那一行）——括号里是出处
    #   · 分级说明——括号里是「哪几节涉及什么、标了什么级」
    # 判据收窄过四次，每次都拿一份故意写坏的样本验过：真正的行文插入语照样报得出来
    # （四段带括号旁白的样本量出 7.94／千字），收掉的只是引注与元信息。
    _skipline = re.compile(r"^\s*(?:前接|后接|对照|相关条目|可串接|参见|延伸|来源|源)[：:]"
                           r"|已就地标注|元层级|分级见各条|就高不就低")
    _body = "\n".join(l for l in t.split("\n") if not _skipline.search(l))
    # 引注／术语注不算病，判据要认得出它们。三类特征，出现任一即放行：
    #   · 指路：见／详见／参见／另见／§／卷号 05-01／13-07
    #   · 计量：百分比、篇数、口径、基数、实测
    #   · 枚举：斜杠分隔的并列项（存储单位/GameBoy/国标）
    # 锚点不能钉在开头——「详辨见 05-易混淆词辨析」「亚型分布报告 §六，关键词口径」
    # 都是指路，只是「见」不在第一个字。钉开头会把它们判成行文里打岔。
    # 判据要认引注，但**不能光看字**。上一版写成「见|篇|条|次」这种裸字，
    # 结果把正常行文吃掉了——「他已经站了快二十分钟，只是不想让她看见」里有「见」，
    # 「这已经是今晚第三次了」里有「次」，两句都是活生生的插入语，却被当成引注放行。
    # 现在一律要求引注的**上下文**：指路词后面得跟得上卷号／书名／章节，
    # 量词前面得有数字。收窄之后拿故意写坏的样本复验过，报得出来。
    _cite = re.compile(r"(?:详见|参见|另见|见)\s*[《§第\d0-9A-Za-z]"
                       r"|§|[%％]|\d{2}-[\d一-鿿]|第\s*[\d一二三四五六七八九十]+\s*[节章卷条部]"
                       r"|\d\s*[篇条页次张部]"
                       r"|口径|基数|实测|来源|出自|同上"
                       r"|[A-Za-z]{3,}"
                       r"|[^／/]+／[^／/]+／")
    # 术语注与行文旁白的分界，看结构不看长度：
    #   注解是**名词短语**——「pegging（女方进入的核心行为）」，里面没有句读，也没有人称
    #   旁白是**带主谓的句子**——「（这已经是今晚第三次了，她自己都数不清）」
    # 百科给术语加注是体例，把话说到一半拿括号补一句才是书面语的手势。
    _aside = re.compile(r"[，,。；;！!？?]|[她他我你它]|[了吗呢吧]$")

    def _is_aside(s):
        return (len(re.findall(r"[一-鿿]", s)) >= 7
                and _aside.search(s) and not _cite.search(s))

    m["长括号/千字"] = round(sum(
        1 for mm in re.finditer(r"[（(]([^（）()\n]{1,60})[）)]", _body)
        if _is_aside(mm.group(1))) / cn * 1000, 2)

    # 句法层
    for k, p in PATTERNS.items():
        m[f"{k}/千字"] = round(len(p.findall(t)) / cn * 1000, 2)

    # 词汇层
    hi = sum(len(re.findall(w, t)) for w in AI_WORDS_HIGH)
    lo = sum(len(re.findall(w, t)) for w in AI_WORDS_LOW)
    m["高危词"] = hi
    m["高危词/千字"] = round(hi / cn * 1000, 2)
    m["低危词/千字"] = round(lo / cn * 1000, 1)
    # 与 check_compliance 的 J 项同一算法：剥掉引文/代码块之后再算，
    # 否则分母偏小、密度虚高（同一篇会出现「J 绿而这里红」的自相矛盾）
    m["加粗/千字"] = round(len(re.findall(r"\*\*[^*\n]{1,40}\*\*", t)) / cn * 1000, 1)
    # 整句被加粗 = 段末金句。加粗密度超标的真身多半是这个：
    # 不是术语强调，是把整句话捧成警句。摘掉星号即可，一个字都不用删。
    m["整句加粗/千字"] = round(
        len(re.findall(r"\*\*[^*\n]{12,}[。！？…]\*\*", t)) / cn * 1000, 2)
    # 中文欧化句法与叙事套话
    m["物理隐喻/千字"] = round(len(METAPHOR_RE.findall(t)) / cn * 1000, 2)
    m["形容词冒号/千字"] = round(len(ADJ_COLON.findall(t)) / cn * 1000, 2)
    for k, pat in CN_WESTERN.items():
        m[f"{k}/千字"] = round(len(pat.findall(t)) / cn * 1000, 2)
    m["小说套话/千字"] = round(sum(t.count(w) for w in FICTION_SLOP) / cn * 1000, 2)
    m["情绪点名/千字"] = round(len(EMOTION_NAMED.findall(t)) / cn * 1000, 2)
    m["行话/千字"] = round(_jargon_hits(t) / cn * 1000, 2)
    for k, pat in HUMANIZER.items():
        m[f"{k}/千字"] = round(len(pat.findall(t)) / cn * 1000, 2)
    return m


# ── 阈值：全部来自语料实测，不是拍脑袋 ──
# 做法：从 5,668 篇真人小说里随机抽 100 篇，各取 2 万字切片，算每个指标的分布。
# 复算：python3 ai_taste.py --baseline
#
#                     真人 P10 / 中位 / P90
#   句长CV              0.55 / 0.67 / 0.84
#   短句占比            0.04 / 0.09 / 0.17
#   不是X是Y/千字       0.00 / 0.00 / 0.18   ← 真人**中位数为 0**
#   破折号插入/千字     0.00 / 0.06 / 1.10
#   特殊用法引号/千字   0.00 / 0.12 / 0.31
#   高危词/千字         0.00 / 0.06 / 0.18
#
# 头两轮我拍过一版阈值，被实测推翻了两条：短句占比定成 ≥0.12（真人中位数才 0.09），
# 「三项列举」当成 AI 特征（真人中位数 7.16，比库里高五倍，中文本来就爱顿号列举）。
# 那条指标已删。**凡是靠直觉定的文风阈值，先去语料里量一遍。**
#
# 百科正文与小说是两种文体：说明文的破折号、术语引号天然多于叙事。
# 所以分两套——叙事类（示例段、开场白、卡片）按真人 P90 收，说明类放宽到 2 倍，
# 唯独「不是X是Y」两套一样严：它不是文体差异，是纯粹的机器腔。
# 破折号**不进硬阈值**，只作参考项打印。
# 理由有两层：①外部研究实测 70 万词已出版文学，破折号密度 4.76/千词，
#   《哈克贝利·费恩》10.13，GPT-4.1 10.62——GPT 只相当于马克·吐温；
#   检测器自己的告警线是 20/千词，通行的「破折号禁令」比人类写作还严。
# ②本库实测：42 张卡按 1.10 的阈值全部触线，逐条看下去，
#   命中的是「——他每年这个时候都不吃枣。谁问他他都说酸。」这类正当插入语。
# 判据误报就改判据，不能拿错判据去逼人改好文字。
# 真正的信号是节奏均匀度（句长 CV），那一项照查。
REFERENCE_ONLY = {"破折号插入/千字"}

HUMAN_P90 = {"不是X是Y/千字": 0.18, "破折号插入/千字": 1.10,
             "特殊用法引号/千字": 0.31, "高危词/千字": 0.18,
             # 欧化句法层，同样是 100 篇真人小说实测的 P90
             "物理隐喻/千字": 0.24, "弱动词/千字": 0.26, "的字连用/千字": 0.43,
             "介词开头/千字": 0.06, "之一/千字": 0.07, "当X之后/千字": 0.12,
             "小说套话/千字": 0.12, "行话/千字": 1.68,
             # 85 篇真人小说实测：中位 0.02，P90 0.21。说明文照惯例给两倍。
             "长括号/千字": 0.21,
             # Humanizer-zh 那七条。真人 P90 实测在 0.00–0.05 之间，
             # 全部取 0.15 —— 比真人 P90 宽三倍以上，说明文再乘 2 得 0.30。
             # 不取更严的值，理由跟破折号那条一样：这七条的词表里有
             # 「一般认为」「批评者指出」这种在考据与争议章节里的正当用法，
             # 阈值贴着真人 P90 收，会把它们逼成一次都不许出现。
             # 0.30 这条线上，本库现文 137 篇一篇不触，坏样本 12 篇全触。
             "意义拔高/千字": 0.15, "句尾浅分析/千字": 0.15, "模糊归因/千字": 0.15,
             "填充短语/千字": 0.15, "过度限定/千字": 0.15, "积极结论/千字": 0.15,
             "连接词/千字": 0.15}

# 真人 P99 都是 0 的三项，零容忍。
# 「问题很直接：」这种「形容词下判断＋冒号」在 100 篇真人小说里一次都没出现过；
# 「他感到一阵……」的情绪点名同理。这不是文体差异，是机器腔的指纹。
HUMAN_ZERO = {"形容词冒号/千字": 0.0, "情绪点名/千字": 0.06, "性度化/千字": 0.06}

# 「整句加粗」单独定，不走语料基线——小说是纯文本，本来就不用 markdown 加粗，
# 拿它的 0 当阈值不诚实。这条的依据是规约铁律 2 本身：
# 加粗只标术语首现与真正的例外。整句话被加粗，两样都不是，它是段末金句。
# 实测：加粗密度超标的篇目，超的几乎全是这一种；摘掉星号即可，一个字不用删。
SENTENCE_BOLD_MAX = 1.0

def limits(narrative=False, prose_cn=None):
    k = 1.0 if narrative else 2.0
    lim = {"句长CV": (0.55, "min"), "短句占比": (0.04, "min"),
           "加粗/千字": (10.0, "max")}
    # 散文太少时不查加粗密度：分母小，密度虚高。
    # 10-藏书索引 那种数据表，散文只有几句，而 `**5,668 篇**` 这类数字强调
    # 是正当的短标签型加粗，硬按 10/千字 查它是拿错尺子。
    # 整句加粗（把整句话捧成警句）不受此限，那个才是真病，照查。
    if prose_cn is not None and prose_cn < 1000:
        lim.pop("加粗/千字")
    # 同理，千字密度类判据在短文上是噪声：11-模板包/去AI味/写作预设 全文 260 字，
    # 只出现一个「配置」，密度就算成 3.83／千字，判它超标说的是那一个词，
    # 不是这篇的写法。散文不足 600 字的，密度类一律不判，只留零容忍词表。
    DENSITY = ("行话/千字", "物理隐喻/千字", "形容词冒号/千字", "小说套话/千字",
               # Humanizer-zh 那七条同样是密度类，短文上同样是噪声
               "意义拔高/千字", "句尾浅分析/千字", "模糊归因/千字", "填充短语/千字",
               "过度限定/千字", "积极结论/千字", "连接词/千字")
    for key, v in HUMAN_P90.items():
        if key in REFERENCE_ONLY:
            continue
        # 「特殊用法引号」只在叙事文里算 AI 腔。百科给术语加引号（「妻主」「np洁癖」）
        # 是体例要求，本库有 350 条术语，按小说标准查它必然满屏误报。
        if key == "特殊用法引号/千字" and not narrative:
            continue
        lim[key] = (round(v * (1.0 if key == "不是X是Y/千字" else k), 2), "max")
    for key, v in HUMAN_ZERO.items():
        lim[key] = (v, "max")
    lim["整句加粗/千字"] = (SENTENCE_BOLD_MAX, "max")
    if prose_cn is not None and prose_cn < 600:
        for k_ in DENSITY:
            lim.pop(k_, None)
    return lim


def verdict(m, narrative=False):
    """判定。千字密度类多一道下限：一处命中不算超标。

    为什么要这道下限：判据剥掉表格与元数据之后，桥段卷的散文只剩两千字上下，
    而「不是X是Y」的阈值是 0.18／千字——两千字的篇目只要出现**一次**，
    算出来就是 0.5，直接判超标。0.18 是真人的 P90，不是零容忍；
    把它套在小分母上，等于偷偷把「少用」改成了「一次都不许用」。
    这是「拿散文的尺量非散文」在这个库里的第四次实例，前三次是
    数据表按散文查密度、短文按千字算密度、句子切分把标题黏进句长。

    下限只给密度类。句长 CV、短句占比是比例不是计数，不适用。
    """
    cn = m.get("汉字") or 1
    bad = []
    for k, (lim, kind) in limits(narrative, m.get("汉字")).items():
        v = m.get(k)
        if v is None:
            continue
        if kind == "min" and v < lim:
            bad.append(f"{k} {v}<{lim}")
        if kind == "max" and v > lim:
            if k.endswith("/千字") and round(v * cn / 1000) <= 1:
                continue        # 全篇就这一处，不构成「密度」
            bad.append(f"{k} {v}>{lim}")
    return bad



def card_texts(lib):
    """把卡里的**叙事字段**抽出来单独查。

    开场白与备选开场是纯小说，读者一打开卡就看到它；
    而 description 是设定表、system_prompt 是指令，两者都不按叙事标准算。
    所以这里只取 first_mes / alternate_greetings / mes_example。
    """
    import json
    for d in ("角色卡", "情景卡", "角色卡-长文本"):
        for f in sorted((lib / "11-模板包" / d).glob("*.json")):
            try:
                data = json.loads(f.read_text(encoding="utf-8")).get("data", {})
            except Exception:
                continue
            # 逐卡豁免与 check_compliance 的 N 项同一套：卡在 creator_notes 里
            # 声明「行话豁免」即跳过。有的卡记账就是那个人的性格（男主-美强惨
            # 把每一份善意折算成债），行话是人物在做的事，不是编者的腔调。
            # 两边口径必须一致，否则会出现「检查器绿而这里红」的自相矛盾。
            if "行话豁免" in (data.get("creator_notes") or ""):
                continue
            t = "\n\n".join([data.get("first_mes", ""), data.get("mes_example", "")]
                             + list(data.get("alternate_greetings") or []))
            if zh(t) >= 300:
                yield f, t


def baseline(n=100, seed=20260822, cut=60000):
    """重算真人基线：从语料随机抽 n 篇，打印每项指标的分位数。

    CLAUDE.md §6 与本文件第 331 行都写着这个命令，但它此前没有实现——
    跑下去会落到「没有可查的文件」那一支，看着像跑过了，其实一个数都没算。
    2026-08 补上。**文档里写了的命令，得真能跑。**

    种子写死，好让阈值可复算。语料是本机私有的，fresh clone 上没有，
    所以这条命令拿不到语料时直接说清楚，不静默出一份空基线。
    """
    corp = CORPUS / "_整理后"
    if not corp.exists():
        print(f"没有语料（找不到 {corp}）。基线只能在有语料的机器上重算。")
        return 1
    files = sorted(corp.rglob("*.txt"))
    if len(files) < n:
        print(f"语料只有 {len(files)} 篇，不足 {n} 篇")
        return 1
    random.seed(seed)
    rows = []
    for f in random.sample(files, n):
        m = measure(f.read_text(encoding="utf-8", errors="ignore")[:cut])
        if m.get("汉字", 0) >= 400:
            rows.append(m)
    keys = [k for k in rows[0] if k.endswith("/千字") or k in ("句长CV", "短句占比")]

    def q(vals, p):
        vals = sorted(vals)
        return vals[min(int(len(vals) * p), len(vals) - 1)]

    print(f"真人基线：{len(rows)} 篇，各取前 {cut//10000} 万字，种子 {seed}\n")
    print(f"{'指标':22}{'P10':>8}{'中位':>8}{'P90':>8}{'P99':>8}")
    print("-" * 54)
    for k in sorted(keys):
        v = [r[k] for r in rows if k in r]
        if not v:
            continue
        cur = HUMAN_P90.get(k)
        mark = ""
        if cur is not None:
            mark = "  ← 现用阈值 %s" % cur
        print(f"{k:22}{q(v,.10):>8.2f}{q(v,.50):>8.2f}{q(v,.90):>8.2f}{q(v,.99):>8.2f}{mark}")
    print("\n改阈值之前先看这张表。凭直觉定的阈值被实测推翻过两次，记在第 341 行。")
    return 0


def card_setting_texts(lib):
    """卡的**设定字段**（personality / scenario）单独成一路。

    2026-08 让外部模型通读全库时发现的洞：--cards 只查开场白三件套，
    这两个字段没有任何检查器在看——而它们是喂给模型的角色定义，
    酒馆每一轮都读，那里的机器腔会顺着流进生成的每一段文本。
    36 张原型卡一量，30 张触线，「不是X是Y」最高 3.67／千字（真人 P90 的 20 倍）。

    口径：设定字段是给机器读的资料卡，不是给读者看的小说，按**说明文标准**
    （narrative=False）收——按小说标准量它是「拿散文的尺量非散文」的第五次实例。
    情景卡的这两个字段普遍不足 300 汉字，密度统计不可靠，门槛照旧。
    """
    import json
    for d in ("角色卡", "情景卡", "角色卡-长文本"):
        for f in sorted((lib / "11-模板包" / d).glob("*.json")):
            try:
                data = json.loads(f.read_text(encoding="utf-8")).get("data", {})
            except Exception:
                continue
            if "行话豁免" in (data.get("creator_notes") or ""):
                continue
            t = "\n\n".join(x for x in (data.get("personality"), data.get("scenario")) if x)
            if zh(t) >= 300:
                yield f, t


def main():
    if "--baseline" in sys.argv:
        return baseline()
    narr = "--narrative" in sys.argv
    if "--cards" in sys.argv:
        rows = [(f, measure(t), verdict(measure(t), True)) for f, t in card_texts(LIB)]
        bad = [(f, b) for f, _, b in rows if b]
        for f, b in bad[:25]:
            print(f"  {f.parent.name}/{f.stem[:28]:30} {'；'.join(b)}")
        print(f"\n卡的叙事字段 {len(rows)} 份，{len(bad)} 份触线（按小说标准）")
        srows = [(f, verdict(measure(t), False)) for f, t in card_setting_texts(LIB)]
        sbad = [(f, b) for f, b in srows if b]
        for f, b in sbad[:35]:
            print(f"  {f.parent.name}/{f.stem[:28]:30} {'；'.join(b)}")
        print(f"卡的设定字段 {len(srows)} 份，{len(sbad)} 份触线（按说明文标准）")
        return 1 if (bad or sbad) else 0
    if "-" in sys.argv:                      # 管道输入
        t = sys.stdin.read()
        m = measure(t)
        bad = verdict(m, narr)
        print(f"{m['汉字']} 汉字，{m.get('句数', 0)} 句")
        for k in ("句长CV", "短句占比", "不是X是Y/千字", "物理隐喻/千字",
                  "整句加粗/千字", "情绪点名/千字", "小说套话/千字"):
            if k in m:
                print(f"  {k:16} {m[k]}")
        print("\n" + ("✗ " + "；".join(bad) if bad else "✓ 未触线"))
        return 1 if bad else 0
    args = [a for a in sys.argv[1:] if not a.startswith("-")]
    # 仓库元文件不按内容卷标准查：它们要引用词表与坏例子来说明规则本身
    # （CHANGELOG 里写「把思考写成物理动作（落地／对齐／接住）」，
    #  那是在讲这个病，不是在犯它）。与 check_compliance 的豁免名单保持一致。
    META = {"CONTRIBUTING.md", "SECURITY.md", "CHANGELOG.md", "CLAUDE.md"}
    if "--lib" in sys.argv:
        # 09-拆解卡 是本地私有、不入库的精读笔记（红线 1.4），check_compliance 的
        # SKIP_DIRS 也排除它。两边口径必须一致，否则本机 ai_taste --lib 会因为
        # 一批根本不在仓库里的文件报红，而贡献者永远修不掉它们。
        files = [p for p in LIB.rglob("*.md")
                 if "_整理后" not in str(p) and ".github" not in p.parts
                 and "09-拆解卡" not in p.parts and "10-藏书索引" not in p.parts
                 and p.name not in META
                 and zh(p.read_text(encoding="utf-8", errors="ignore")) > 800]
    else:
        files = []
        for a in args:
            p = Path(a)
            # 收 .txt：创作者的稿子多是 txt，只收 .md 会打印「0 篇，0 篇触线」
            # 并返回 0——看着全绿，其实一个字都没查。这是唯一一个会
            # 主动制造虚假安全感的坑。
            files += (sorted(x for x in p.rglob("*")
                             if x.suffix.lower() in (".md", ".txt"))
                      if p.is_dir() else [p])
    if not files:
        print("没有可查的文件（只认 .md 与 .txt）")
        return 1
    rows = []
    for f in files:
        m = measure(f.read_text(encoding="utf-8", errors="ignore"))
        rows.append((f, m, verdict(m, narr)))
    rows.sort(key=lambda r: -len(r[2]))
    for f, m, bad in rows[:40]:
        rel = f.relative_to(LIB) if str(f).startswith(str(LIB)) else f
        flag = "✗ " + "；".join(bad) if bad else "✓"
        print(f"{str(rel)[:44]:46} CV{m.get('句长CV','-'):>5} 短{m.get('短句占比','-'):>5} "
              f"高危{m['高危词']:>3} {flag}")
    n_bad = sum(1 for _, _, b in rows if b)
    print(f"\n{len(rows)} 篇，{n_bad} 篇触线")
    if rows:
        cvs = [m["句长CV"] for _, m, _ in rows if "句长CV" in m]
        if cvs:
            print(f"全库句长 CV 中位数 {statistics.median(cvs):.2f}"
                  f"（越高越像人写的；<0.55 视为过齐）")
    return 1 if n_bad else 0


if __name__ == "__main__":
    sys.exit(main())
