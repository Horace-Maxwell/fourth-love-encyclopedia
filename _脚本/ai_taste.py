def _jargon_hits(t):
    """行话命中数，剔掉放行名单里的日常词。

    命中的是「双字+源/感/力」，而日常词常是四字（专业能力／法律效力）——
    正则只截到「业能力」「律效力」，跟名单对不上。所以连同左边一个字
    一起比一次：三种切法有一种在名单里，就放行。
    """
    n = 0
    for m in JARGON_RE.finditer(t):
        w = m.group(0)
        wider = t[max(0, m.start() - 1):m.end()]      # 往左多取一字
        if w in JARGON_OK or wider in JARGON_OK or w[-2:] in JARGON_OK:
            continue
        n += 1
    return n


