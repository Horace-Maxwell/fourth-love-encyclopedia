# ── 把人的日子翻译成会计、工程与管理的术语 ──   # 例外:M 词表本身不是病
# 这一族比「物理动作隐喻」更致命：物理隐喻只是几个动词，这一族是**整套说话方式**。
# 实测：真人小说中位 0.95/千字、P90 1.68、最高 3.65；本库中位 5.60，是真人的六倍。
#
# 病例（用户圈出来的三处，全在同一条桥段里）：
#   「桌下越界，家宴就换了张力源」
#   「维持一个身份的成本按天结算，掉马前夜结的是总账」
#   「早起的四十分钟乘一年，就是她欠身体的账」
# 三句都在把「人过日子」写成「系统在结算」。读者要的是那四十分钟本身，
# 不是那四十分钟的折现值。
#
# 改法一律是**换成具体**，不是换个近义词：
#   欠身体的账 → 一年下来，早上那四十分钟她再没睡回来过
#   张力源     → 桌上的人会看，桌下的人会怕
#   情感杠杆   → 拿他妈妈的病压他
#
# 元层豁免：讲方法的地方可以用「判据／口径／节拍链」这类术语，那是本库的体例；
# 写场面、写人物、写细节的地方不能用。所以这一项按**叙事口径**收严、说明口径放宽。
