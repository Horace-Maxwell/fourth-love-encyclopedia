# ══ 水印与噪声清洗 ════════════════════════════════════════════════════
# 资源搬运站会在文件名与文案里插入自己的水印，其中「公主号」（公众号的规避写法）
# 会把「公主」这个人设词污染到 900+ 篇。不清洗则全部人设统计失真。
WATERMARK = re.compile(
    r"【?(?:公主号|公众号|公號|微信|VX|vx|qq群|QQ群|微博)[:：]?[^】\]\)）\n]{0,20}】?"
    r"|【?笨笨书屋】?|【?[^】\n]{0,10}书屋】?|【?[^】\n]{0,8}整理】?"
    r"|【?MJ】?|【?文文】?|【?密码\d*】?|【?棠】?"
    r"|本作品来自互联网[^\n]{0,40}|内容版权归[^\n]{0,30}"
    r"|小说下载尽在[^\n]{0,40}|书香门第[^\n]{0,20}"
    r"|更新请加[^\n]{0,40}|欢迎加入[^\n]{0,30}|扫码[^\n]{0,20}")


def clean(s: str) -> str:
    return WATERMARK.sub(" ", s)


def tag_text_of(r):
    """把一篇的全部自述文本拼起来，供标签匹配。"""
    b = r.get("文案", {})
    parts = [clean(r["文件名"])]
    for k in ("方括号标签", "斜杠标签", "内容标签", "搜索关键字", "一句话简介",
              "站头分类", "站头体裁", "CP", "文章类型", "作品视角"):
        if k in b:
            parts.append(clean(b[k]))
    return " ".join(parts)


def full_blurb_of(r):
    """完整自述（含长文案与排雷），供人设/套路词挖掘。"""
    b = r.get("文案", {})
    parts = [tag_text_of(r)]
    for k in ("文案", "内容简介", "排雷", "作品简评", "立意", "主角", "配角"):
        if k in b:
            parts.append(clean(b[k]))
    return " ".join(parts)


