def classify_inclusion(r):
    """返回 (是否入库, 理由)。"""
    name = r["文件名"]
    blob = tag_text_of(r)
    has_gb = any(g in blob for g in GB_MARK)
    if has_gb:
        return True, ""
    # 以下都是「没有任何 GB 标记」的情况，逐条排查
    for w in KNOWN_BL:
        if w in name:
            return False, f"已知 BL 作品（{w}）"
    for w in MALE_ORIENTED:
        if w in name:
            return False, f"男性向标记（{w}）"
    if r["万字"] >= 100:
        return False, f"无 GB 标记的巨型合集（{r['万字']}万字）"
    she = r["她占比"]
    if she < 0.10 and r["我占比"] < 0.35:
        return False, f"第三人称叙事下她占比极低（{she}），疑似 BL"
    if r["女尊词"] >= 5:
        return True, ""          # 正文有制度词，虽无标签也算
    return False, "无任何 GB 标记且无制度词旁证"


