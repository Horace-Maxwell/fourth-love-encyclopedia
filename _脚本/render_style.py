# ══ 去 AI 化出口（00-编纂规约/05 的七条铁律）═══════════════════════════
# 所有渲染结果统一走这里出。理由：本卷是脚本生成的，靠人工盯文风盯不住，
# 而铁律是可测的（加粗 ≤10/千字、破折号追加 ≤1/千字），那就让脚本自己保证。
_HINT = re.compile(r"(值得注意的是|值得记一下|这才是关键|需要指出的是|请注意)[，,：:]?\s*")  # 例外:M 清洗正则是药不是病


BOLD = re.compile(r"\*\*([^*\n]+)\*\*")


def _bold_pass(line):
    """一行里最多留一处加粗，且那一处必须短到真有强调作用。

    与 render_mining.py 的同名函数同一份实现，修的是同一个错误：
    早先这里是两条独立的 re.sub，第一条 `\\*\\*([^*\\n]{11,})\\*\\*`
    不认「哪个 ** 是开、哪个是收」，会从**第一段的收尾符**匹配到
    **第二段的起始符**，把两段之间的普通文字当成超长加粗给「去粗」，
    结果反而把两段之间的空隙加粗了。实测：

        输入  这是**第一处加粗**，中间隔了足够长的一段文字，然后是**第二处加粗**。
        旧输出 这是**第一处加粗，中间隔了足够长的一段文字，然后是第二处加粗**。

    整句被这样「加粗」出来，正是 ai_taste 的「整句加粗」判据要抓的东西——
    去 AI 化的出口自己在造 AI 味。改成先按左起非重叠切出配对的加粗段，再逐段判定。
    """
    spans = list(BOLD.finditer(line))
    if not spans:
        return line
    keep = next((k for k, m in enumerate(spans) if len(m.group(1)) <= 10), None)
    out, last = [], 0
    for k, m in enumerate(spans):
        out.append(line[last:m.start()])
        out.append(m.group(0) if k == keep else m.group(1))
        last = m.end()
    out.append(line[last:])
    return "".join(out)


def deai(text):
    out = []
    for line in text.split("\n"):
        if line.lstrip().startswith("|"):
            # 表格已经提供结构，格内加粗是重复
            out.append(BOLD.sub(r"\1", line))
            continue
        line = _bold_pass(line)
        # 破折号追加解释 → 断句
        line = re.sub(r"([。！？])——([^\n]{6,})", r"\1\2", line)
        line = re.sub(r"([^。！？\n])——([^\n—]{8,}?)([。！？])", r"\1。\2\3", line)
        out.append(_HINT.sub("", line))
    return "\n".join(out)


