# 抽取时名字尾部会粘上下一个词（「路菲冲他」「顾修明失」「闻人枢却」）。
# 单篇里量小看不见，聚合后集中冒到四字名一栏。
TAIL_JUNK = re.compile(r"(冲他|冲她|看他|看她|无奈|失笑|却|也|都|还|又|就|才|便|已|竟|"
                       r"猛地|忽然|终于|这才|轻轻|淡淡|冷冷|缓缓)$")


def _strip_tail(n):
    for _ in range(2):
        n2 = TAIL_JUNK.sub("", n)
        if n2 == n or len(n2) < 2:
            break
        n = n2
    return n


def _fold(c):
    """尾部粘连归并回本名，并剔除含代词的伪名。"""
    out = Counter()
    for n, v in c.items():
        n = _strip_tail(n)
        if len(n) >= 2 and not re.search(r"[他她你我们]", n):
            out[n] += v
    return out


def clean_names():
    """人名：去通名、去尾部粘连、去跨性别重复。"""
    f, m = _fold(C("names_f")), _fold(C("names_m"))
    for g in GENERIC:
        f.pop(g, None)
        m.pop(g, None)
    # 性别标注只在**跨书一致性 ≥75%** 时才敢下；否则一律归入「难判」。
    # 早先门槛是 45%，等于「多数票就算数」——在逐书推断本身有噪声的前提下，
    # 那个门槛会把一半的错误推断当成结论输出。
    both = set(f) & set(m)
    amb = Counter()
    for n in both:
        hi, lo = max(f[n], m[n]), min(f[n], m[n])
        if hi / (hi + lo) < 0.75:
            amb[n] = f[n] + m[n]
            f.pop(n), m.pop(n)
        elif f[n] > m[n]:
            m.pop(n)
        else:
            f.pop(n)
    x = _fold(C("names_x"))
    for g in GENERIC:
        x.pop(g, None)
    return f, m, amb + x


