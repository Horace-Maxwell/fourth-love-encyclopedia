def mine_one(path_str: str):
    """单篇。只回传计数与结构，不回传任何原文。"""
    try:
        text = decode_bytes(Path(path_str).read_bytes())
    except OSError:
        return None
    text = text.replace("\r\n", "\n").replace("\r", "\n")[:SAMPLE]
    if len(text) < 3000:
        return None

    # 全文标记位置
    marks = []
    for name, p in PAT.items():
        for m in p.finditer(text):
            marks.append((m.start(), name))
    marks.sort()
    # 节拍族计数只统计**落在命中窗口里**的，不统计全书 presence。
    # 60 万字的书里必然出现「哭」，书级 presence 一律 90%+，不携带信息。
    fam_present = set()

    # 扫窗口找共现簇。命中后**跳到窗口末尾**再继续，不让相邻窗口重叠：
    # 重叠窗口会把同一场戏按标记个数重复计数，且道具正则要在同一段文字上
    # 反复跑几十遍（长篇里标记上千个，实测能把单篇耗时拉高两个数量级）。
    # 跳过之后，一次命中 = 一场戏。
    combos, seqs, props, worlds = set(), set(), set(), set()
    n = len(marks)
    i = 0
    while i < n:
        j = i
        while j < n and marks[j][0] - marks[i][0] <= WIN:
            j += 1
        seq = [nm for _, nm in marks[i:j]]
        uniq = set(seq)
        if (len(uniq & SCENE_KEYS) >= MIN_SCENE
                and len(uniq & REACT_KEYS) >= MIN_REACT):
            fam_present |= uniq
            # 组合签名只用情境族——反应族在哪一场戏里都可能出现，
            # 把它们写进签名会让同一个桥段裂成十几个组合。
            combos.add("+".join(sorted(uniq & SCENE_KEYS)))
            worlds |= uniq & WORLD_KEYS
            # 有序节拍链：去重但保留首次出现顺序——这是「节拍链」那一格的数据源
            ordered, seen = [], set()
            for s in seq:
                if s not in seen:
                    ordered.append(s); seen.add(s)
            seqs.add("→".join(ordered[:6]))
            # 只在命中窗口内数道具，数到的才是日常戏的道具而非全书的道具。
            # 同时记下它出现在哪个情境族的窗口里——这决定它进哪一条桥段的细节清单。
            span = text[marks[i][0]: marks[j - 1][0] + 60]
            scenes_here = uniq & SCENE_KEYS
            for w, _dom in PROP_WORDS:
                if w in span:
                    props.add(w)
                    for sc in scenes_here:
                        props.add(f"{sc}\t{w}")
            i = j          # 命中即跳过整窗
        else:
            i += 1

    return {
        "fam": sorted(fam_present),      # 本篇出现过哪些节拍族
        "combo": sorted(combos),         # 本篇出现过哪些共现组合
        "seq": sorted(seqs),             # 本篇出现过哪些有序节拍链
        "prop": sorted(props),           # 本篇桥段窗口里的道具
        "world": sorted(worlds),         # 本篇属于哪些世界设定
        "hit": bool(combos),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--workers", type=int, default=max(2, (os.cpu_count() or 4) - 2))
    ap.add_argument("--limit", type=int, default=0)
    a = ap.parse_args()

    # 按**独立作品**挖，不按文件挖。理由同 mine_text：
    # 同一部作品的多份存档会让单篇的独特结构靠副本凑够篇数、冒充成类型套路。
    from aggregate_corpus import R as KEEP, _norm_t
    best = {}
    for r in KEEP:
        t = _norm_t(r.get("文件名") or r["path"].rsplit("/", 1)[-1])
        if t not in best or r["字数"] > best[t]["字数"]:
            best[t] = r
    files = [r["path"] for r in best.values()]
    if a.limit:
        files = files[:a.limit]
    print(f"待挖掘 {len(files):,} 部独立作品，{a.workers} 进程\n")

    fam = Counter(); combo = Counter(); seq = Counter(); prop = Counter()
    world = Counter()
    docs = hits = done = 0
    with ProcessPoolExecutor(max_workers=a.workers) as ex:
        futs = [ex.submit(mine_one, f) for f in files]
        for fut in as_completed(futs):
            done += 1
            try:
                r = fut.result()
            except Exception:
                r = None
            if r:
                docs += 1
                hits += r["hit"]
                fam.update(r["fam"]); combo.update(r["combo"])
                seq.update(r["seq"]); prop.update(r["prop"])
                world.update(r["world"])
            if done % 300 == 0:
                print(f"  {done:,}/{len(files):,}")

    print(f"\n有效 {docs:,} 部｜含桥段 {hits:,} 部 ({hits/max(docs,1)*100:.0f}%)")

    OUT.write_text(json.dumps({
        "docs": docs,
        "hits": hits,
        "win": WIN,
        "min_scene": MIN_SCENE,
        "min_react": MIN_REACT,
        "fam": fam.most_common(),
        "combo": combo.most_common(400),
        "seq": seq.most_common(400),
        # 全局道具频次（跨 ≥8 部不同作品才留）
        "prop": [(w, c) for w, c in prop.most_common() if "\t" not in w and c >= 8],
        # 道具 × 情境族：某个物件主要出现在哪一场戏里，供各条桥段的细节清单取用
        "prop_by_scene": [(w, c) for w, c in prop.most_common() if "\t" in w and c >= 5],
        "prop_lex": {d: s.split() for d, s in PROP_LEX.items()},
        "world": world.most_common(),
    }, ensure_ascii=False), encoding="utf-8")
    print(f"→ {OUT.relative_to(LIB)}")


if __name__ == "__main__":
    main()
