#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
把 13 卷挖出来的权力语言做成可直接导入的世界书包。

为什么单独做一个包而不是靠 12-导出 的全库包：
  全库包是**按文档切块**的——每条对应主库的一节，适合「查资料」。
  RP 时需要的是另一种形态：**一条一个可执行约束**，且必须常驻，
  因为语言习惯要在每一楼都生效，靠关键词触发就晚了。

  实测教训（见 12-导出/README）：常驻条目每条都在花 token，所以这个包
  常驻的只有真正需要每楼遵守的 4 条，其余靠关键词进场。

数据来自 `10-藏书索引/_正文挖掘.json`，与 13 卷同源，**改语料重跑即可**。

用法：python3 build_langpack.py
"""

import json
from collections import Counter
from pathlib import Path

from paths import LIB

SRC = LIB / "10-藏书索引" / "_正文挖掘.json"
OUT = LIB / "11-模板包" / "世界书" / "权力语言包.json"

D = json.loads(SRC.read_text(encoding="utf-8"))
cmd = Counter({k: v for k, v in D["cmd"]})
sub = Counter({k: v for k, v in D["submit"]})
pos = Counter({k: v for k, v in D["possess"]})
scene = D["scene"]
DOCS = D["docs"]

# 称谓实例：与 13 卷同一套版权门槛（≤16 字、跨 ≥5 篇 = 类型套话而非作者表达）
tex = {t: [(s, n) for s, n in ex if len(s) <= 16 and n >= 5][:6]
       for t, ex in D["title_ex"].items()}
tex = {t: v for t, v in tex.items() if v}

E = []


def add(name, content, keys=(), const=False):
    E.append({
        "keys": list(keys),
        "name": name,
        "content": content,
        "constant": const,
        "enabled": True,
        "position": "before",
    })


# ══ 常驻 4 条：语言习惯必须每楼生效 ═══════════════════════════════════
add("【常驻】★ 命令句：短到不能再短",
    "女攻下令时**句子必须短**。全语料统计：命令句榜首清一色二到三字加句号。\n\n"
    "**规则**\n"
    "- 命令句控制在 2–6 字，句号收尾\n"
    "- **命令后不接解释**——解释是请求的语法（「过来，我有话跟你说」＝请求）\n"
    "- **不用问号**（「你过来好吗」把决定权交回去了）\n"
    "- 需要软化时，用**降低音量**而不是拉长句子\n\n"
    f"**高频实例**（按出现篇数）：{'　'.join(c for c, _ in cmd.most_common(24))}\n\n"
    "**反向用法**：想写权力松动，就让她的命令句突然变长。不必写「她心软了」，句子长度自己会说。",
    const=True)

add("【常驻】★ 顺从要写意志，不要只写身体",
    "全语料统计暴露了这个类型最大的写作惯性：\n\n"
    "| 档 | 词 | 量级 |\n|---|---|---:|\n"
    + "\n".join(f"| 生理性不自主 | {k} | {v:,} |" for k, v in sub.most_common(3))
    + "\n"
    + "\n".join(f"| **意志性顺从** | **{k}** | {v:,} |"
               for k, v in sub.most_common() if k in ("听话", "讨好", "顺从", "认错"))
    + "\n\n"
    "**前三名全是身体失控，意志性顺从低一个数量级。**\n\n"
    "**规则**：写他顺从时，优先写**他做了一个选择**（听话／退让／认错／主动请罚），"
    "而不是只写身体反应（喘／抖／跪）。身体反应不是不能用，是**不能只用它**——"
    "只写身体，读者看到的是生理事件，不是关系事件。",
    const=True)

add("【常驻】★ 占有用陈述句，不用命名",
    "全语料统计：占有欲主要通过**陈述事实**表达，不是通过给对方安称呼。\n\n"
    + "　".join(f"`{k}`({v:,})" for k, v in pos.most_common(6)) + "\n\n"
    "「是我的」压倒性第一，且它是**判断句**。\n"
    "**「我的狗」这类带贬抑的称呼量级低两个数量级**——它是重口一档的标记词，"
    "用它等于给这一楼贴了预警 tag。除非确实要走那个方向，否则不要用。",
    const=True)

add("【常驻】★ 称谓换档就是情节",
    "称谓不是称呼，是**权力状态的读数**。同一组关系至少有三档：\n\n"
    "| 档 | 场合 | 特征 |\n|---|---|---|\n"
    "| 公开 | 有第三人在场 | 位分词，完整称谓 |\n"
    "| 私下 | 只有两人 | 简称、名字、昵称 |\n"
    "| 失控 | 情绪临界 | 回到最正式的那一档，**或**掉到最亲密的那一档 |\n\n"
    "**换档本身就是情节点。** 不要平白无故换，也不要一整本书不换。\n"
    "**掉档比升档有戏**——她突然叫全名，比她突然叫昵称更有信息量。",
    const=True)

# ══ 关键词触发：称谓的真实用法 ═══════════════════════════════════════
GROUPS = [
    ("女尊位分", ["妻主", "正君", "侧君", "侍君", "贵君", "君后", "夫郎", "夫侍", "男妻"]),
    ("宫廷", ["陛下", "殿下", "太女", "帝卿", "王爷", "王君", "大人"]),
    ("亲属", ["父君", "父后", "小爹", "姐姐", "哥哥", "弟弟"]),
    ("主奴", ["主人", "奴家"]),
    ("现代", ["先生", "小姐", "老板", "公子", "少爷", "娘子", "郎君"]),
    ("师门军职", ["师尊", "师父", "将军", "元帅"]),
]
for gname, titles in GROUPS:
    body = []
    for t in titles:
        if t in tex:
            body.append(f"**{t}**　" + "　".join(f"`{s}`" for s, _ in tex[t][:5]))
    if not body:
        continue
    add(f"称谓实例 · {gname}",
        f"下列是从 {DOCS:,} 篇正文里抽出的**真实用法**，全部为 ≤16 字、跨 ≥5 篇的类型套话"
        "（不是任何单一作者的表达）。它们告诉你这个称谓被说出口时是什么形状。\n\n"
        + "\n\n".join(body)
        + "\n\n**用法**：照着这个长度与语气写，不要把称谓塞进长句里——"
          "位分词一旦出现在从句中间，它就从「权力标记」降格成「普通名词」。",
        keys=titles)

# ══ 关键词触发：名场面出现率 ═══════════════════════════════════════
tot = sum(scene.values())
rows = "\n".join(f"| {k} | {v/tot*100:.1f}% |"
                 for k, v in sorted(scene.items(), key=lambda x: -x[1]))
add("名场面 · 读者在等哪几场戏",
    f"十类名场面在 {DOCS:,} 篇正文里的实际出现率：\n\n| 场景 | 占比 |\n|---|---:|\n{rows}\n\n"
    "**三条可操作的读法**\n"
    "1. **「破防时刻」高居前列 → 这个类型的情绪高点在男受身上。** "
    "女攻负责施加，男受负责承受与破防，读者的情绪投资落在被动一方。\n"
    "2. **「称谓改变」排名极高，且是十类里唯一纯语言性的。** "
    "它不需要任何情节支撑，成本最低，效果排进前三——**投入产出比最高的一场戏**。\n"
    "3. **「第一次触碰」命中率垫底，但读者讨论热度远高于此。** "
    "写得少、被记得多，**稀缺项，写好了辨识度极高**。",
    keys=["名场面", "高光", "转折", "破防", "下马威", "改口", "跪"])

OUT.write_text(json.dumps({"project": "第四爱模板包", "entries": E},
                          ensure_ascii=False, indent=1), encoding="utf-8")
print(f"→ {OUT}")
print(f"  {len(E)} 条（常驻 {sum(1 for e in E if e['constant'])} 条）")
print(f"  常驻总字数 {sum(len(e['content']) for e in E if e['constant']):,}")
for e in E:
    print(f"    {'★' if e['constant'] else ' '} {e['name'][:40]:42} {len(e['content']):>5} 字")
